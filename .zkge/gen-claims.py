def yaml_list(items, indent=4):
    pad = " " * indent
    if not items:
        return " []"
    return "\n" + "\n".join(f"{pad}- {i!r}" for i in items)


def render(c):
    (cid, stmt, srcs, otype, oexpr, cexpr, incl, excl, asm, vers, assurance) = c
    return f"""# 来源能力问题：{', '.join(srcs)}
schema: zkge.claim/v1
id: {cid}
statement: {stmt!r}
owner: product.rtc
risk_level: R3
required_assurance_level: {assurance}
scope:
  included:{yaml_list(incl)}
  excluded:{yaml_list(excl)}
assumptions:
  - id: ASSUMPTION.{cid.split('.', 1)[1]}
    text: {asm!r}
oracle:
  type: {otype}
  expression: {oexpr!r}
counterexample:
  expression: {cexpr!r}
required_verifiers:{yaml_list(vers)}
invalidation_inputs:
  - specification_digest
  - source_digest
  - artifact_digest
  - verifier_digest
status: UNKNOWN
"""


def main():
    os.makedirs(OUT, exist_ok=True)
    ids = set()
    for c in CLAIMS:
        cid = c[0]
        assert cid not in ids, f"重复 ID: {cid}"
        ids.add(cid)
        assert cid.startswith("CLAIM.") and cid.count(".") == 2, f"ID 格式非法: {cid}"
        with open(os.path.join(OUT, cid + ".yaml"), "w", encoding="utf-8") as f:
            f.write(render(c))
    # 移除模板占位文件
    example = os.path.join(OUT, "CLAIM.EXAMPLE.001.yaml")
    if os.path.exists(example):
        os.remove(example)
        print("已移除模板占位：CLAIM.EXAMPLE.001.yaml")
    print(f"生成 claim 文件：{len(CLAIMS)} 份")


if __name__ == "__main__":
    main()